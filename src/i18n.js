function savedLocale() {
  try {
    const saved = localStorage.getItem("locale");
    if (saved in messages) return saved;
  } catch {}
  const lang = navigator.language ?? "";
  if (lang.startsWith("ru")) return "ru";
  if (lang.startsWith("zh")) return "zh";
  return "en";
}

